import { deepFreeze, type EntityType, type FieldDef, type IndustryPack } from '../../core/pack-api.js';

const price = (key: string, label: string, required = true): FieldDef => ({
  key,
  label,
  type: 'money',
  decimals: 2,
  unitFrom: 'unit',
  group: 'pricing',
  required,
  reprices: true,
});
const count = (key: string, label: string, min: number, required = true): FieldDef => ({
  key,
  label,
  type: 'intUnit',
  min,
  group: 'pricing',
  required,
  reprices: true,
});
export const partEntity: EntityType = deepFreeze({
  kind: 'part',
  label: '工业品',
  icon: 'box',
  codeLabel: '零件编号',
  codeExample: 'bearing-01',
  titleKey: 'partNo',
  subtitleKeys: ['$code', 'name'],
  groups: [
    { key: 'basic', label: '产品信息' },
    { key: 'pricing', label: '价格与交期' },
  ],
  lockGroups: { identity: { tag: '上架后锁定', reason: '型号、类别与单位用于识别已发出的报价' } },
  fields: [
    { key: '$code', label: '零件编号', type: 'text', group: 'basic' },
    { key: 'partNo', label: '型号', type: 'text', group: 'basic', lockedWhenActive: true, lockGroup: 'identity' },
    { key: 'name', label: '品名', type: 'text', group: 'basic' },
    { key: 'brand', label: '品牌', type: 'text', group: 'basic' },
    {
      key: 'category',
      label: '类别',
      type: 'enum',
      options: ['轴承', '紧固件', '气动元件', '低压电器'],
      group: 'basic',
      lockedWhenActive: true,
      lockGroup: 'identity',
    },
    { key: 'specs', label: '规格', type: 'tags', group: 'basic' },
    {
      key: 'unit',
      label: '单位',
      type: 'enum',
      options: ['件', '个', '套', '米', '千克', '盒'],
      group: 'basic',
      lockedWhenActive: true,
      lockGroup: 'identity',
    },
    price('unitPrice', '基础单价'),
    count('moq', '起订量', 1),
    ...[2, 3, 4].flatMap((n) => [count(`tier${n}Qty`, `第${n}档数量`, 1, false), price(`tier${n}Price`, `第${n}档单价`, false)]),
    count('stock', '现货数量', 0),
    count('leadDays', '交期天数', 0),
    ...[
      ['aliases', '别名'],
      ['substitutes', '替代型号'],
      ['certs', '认证'],
    ].map(([key, label]) => ({ key: key!, label: label!, type: 'tags' as const, group: 'basic', required: false })),
    { key: '$status', label: '状态', type: 'status', group: 'basic' },
  ],
  itemRules: [
    { kind: 'ascending', keys: ['tier2Qty', 'tier3Qty', 'tier4Qty'] },
    { kind: 'descending', keys: ['unitPrice', 'tier2Price', 'tier3Price', 'tier4Price'] },
    { kind: 'greaterThan', key: 'tier2Qty', other: 'moq' },
    ...[2, 3, 4].map((n) => ({ kind: 'together' as const, keys: [`tier${n}Qty`, `tier${n}Price`] })),
    { kind: 'contiguous', keys: ['tier2Qty', 'tier3Qty', 'tier4Qty'] },
  ],
  list: {
    columns: ['partNo', 'name', 'unitPrice', 'stock', '$status', '$updated'],
    filters: ['category'],
    search: ['$code', 'partNo', 'name', 'aliases'],
    defaultSort: '-$updated',
  },
  csvImport: true,
  activateLine: '上架后，顾问可按此型号提供询价服务',
});
