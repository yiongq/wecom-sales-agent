// 跟进的拒绝识别（docs/architecture/02-conversations-workbench/spec.md「任务表与跟进」）：客户说「不用了」「别发了」「不需要了」
// 「已经订别家了」「不考虑了」这类话，记 followupOptOut，此后这个会话不再有跟进（不变量 38）。两种存储共用，引擎记下客户原话时调。
// 纯函数：不 import store、engine、llm。
//
// 按小句判，整个小句就是拒绝才算，疑问与否定排除。不按子串收「不用」「算了」（plan「实施记录 · 第 1 步」第 8 类）：
// 「先不用发方案了，我再想想」（不用发的是方案）、「不用再看看了，就订这个」（要成交）、「不用倒时差」「算了 就这个吧 订」
// 「别的不考虑」都不是拒绝。「先」「暂时」开头的（「先不用了」「暂时不考虑了」）说的是现在不要，也不算：跟进本来就隔几个小时。

/** 小句边界：中英文标点、空白（微信里常用空格断句）。问号单独记下，用来排除疑问 */
const CLAUSE_SPLIT = /([，,。.！!？?；;、～~…\s]+)/;
/** 小句开头的应答、语气词，去掉之后再整句比对（「好的不用了」「那就不考虑了」「算了不用了」） */
const LEAD = /^(?:嗯+|哦+|噢+|啊|好的?|行|那就?|那我|算了|谢谢|谢了|多谢|真的|其实|我们?)+/;
/** 句末的客气话与语气词（「不用了谢谢」「别发了哈」）。吗、呢、么、嘛、吧不在里面：带着它们的是在问或在犹豫 */
const TAIL = /(?:谢谢(?:你|您|啦|了)?|哈+|啊|呀|啦|哦+|噢|喔|哟|嗷)+$/;
const ASKING = /[吗呢么嘛吧]$/;

const OPT_OUT: readonly RegExp[] = [
  // 不用了、不需要了、都不用了
  /^(?:都|也|真)?(?:不用|不需要|不必)了$/,
  // 别发了、别再发了、不要再给我发消息了、不用再联系我了、别打扰我了（「不用发了」没有「再」，多半说的是不用发某样东西，不算）
  /^(?:你们?|您)?(?:别再?|甭再?|不要再?|不用再)(?:给我|跟我|和我)?(?:发|推|推送|打扰|骚扰|联系|烦)(?:我|消息|信息)?(?:给我)?了$/,
  // 已经在别家订了、已经订了别家的了
  /^(?:已经|已)(?:在)?(?:别家|别的地方|别处|其他家|其它家|其他平台|其它平台)(?:订|定|买|报|下单)(?:好)?了$/,
  /^(?:已经|已)(?:订|定|买|报)(?:了|好了)?(?:别家|别的家|其他家|其它家)(?:的)?了?$/,
  // 不考虑了、就不考虑了
  /^(?:就|都)?不考虑了$/,
];

/** 这一小句（已去掉边界标点）是不是拒绝跟进 */
function clauseOptsOut(raw: string, asked: boolean): boolean {
  const c = raw.trim();
  if (!c || asked || ASKING.test(c)) return false;
  const core = c.replace(TAIL, '').replace(LEAD, '');
  return OPT_OUT.some((re) => re.test(core));
}

/** 客户这句话里有没有一个小句明确拒绝跟进 */
export function followupOptOutOf(text: string): boolean {
  const parts = text.split(CLAUSE_SPLIT);
  // split 带捕获组：奇数位是边界，偶数位是小句。边界里有问号，前面那一小句就是在问
  for (let i = 0; i < parts.length; i += 2) {
    const sep = parts[i + 1] ?? '';
    if (clauseOptsOut(parts[i] ?? '', /[？?]/.test(sep))) return true;
  }
  return false;
}
