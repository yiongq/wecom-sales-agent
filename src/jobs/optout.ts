// 跟进的拒绝识别（docs/architecture/02-conversations-workbench/spec.md「任务表与跟进」）：客户说「不用了」「别发了」「不需要了」
// 「已经订别家了」「不考虑了」这类话，记 followupOptOut，此后这个会话不再有跟进（不变量 38）。两种存储共用，引擎记下客户原话时调。
// 纯函数：不 import store、engine、llm。
//
// 按小句判：这条消息里有一个小句整句就是拒绝，而且其余每个有内容的小句要么也是拒绝、要么只是客气话或应答（谢谢、好的、嗯、哦、
// 拜拜、再见、ok……），才算。有任何别的小句就不算：「不用了，就订这个」「不考虑了，看看云南吧」「好的不用了，帮我改成3个人」
// 是在成交、问询、改需求、看别的线路，那句「不用了」谢绝的是某个附加项，不是跟进（审查之后改的，原来一个小句命中就算）。
// 疑问与否定排除。不按子串收「不用」「算了」（plan「实施记录 · 第 1 步」第 8 类）：「先不用发方案了，我再想想」（不用发的是方案）、
// 「不用再看看了，就订这个」（要成交）、「不用倒时差」「算了 就这个吧 订」「别的不考虑」都不是拒绝。「先」「暂时」开头的
// （「先不用了」「暂时不考虑了」）说的是现在不要，也不算：跟进本来就隔几个小时。
// 判之前先归一：全角转半角、英文转小写、繁体常用字转简体，emoji 与微信表情码（[微笑]）当分隔，破折号、连字符也当分隔，
// 小句里连着说两遍的折成一遍（「不用了不用了」）。

/** 繁体常用字 → 简体：只收拒绝说法与客气话里会出现的字 */
const TRAD: Record<string, string> = {
  別: '别',
  發: '发',
  慮: '虑',
  經: '经',
  訂: '订',
  謝: '谢',
  們: '们',
  給: '给',
  擾: '扰',
  騷: '骚',
  聯: '联',
  繫: '系',
  係: '系',
  煩: '烦',
  處: '处',
  買: '买',
  報: '报',
  單: '单',
  臺: '台',
  後: '后',
  請: '请',
  託: '托',
  嗎: '吗',
  麼: '么',
  見: '见',
  沒: '没',
  訊: '讯',
  說: '说',
  説: '说',
  這: '这',
  個: '个',
};
const TRAD_RE = new RegExp(`[${Object.keys(TRAD).join('')}]`, 'g');
/** emoji（含肤色、变体选择符、零宽连接）与微信表情码「[微笑]」「[捂脸]」「[OK]」：当成分隔 */
const EMOJI = /[\p{Extended_Pictographic}\p{Emoji_Modifier}\p{Variation_Selector}\p{Join_Control}]/gu;
const WECHAT_FACE = /\[[^[\]\s]{1,8}\]/g;

/** 小句边界：中英文标点、破折号与连字符、括号引号、空白（微信里常用空格断句）。问号单独记下，用来排除疑问 */
const CLAUSE_SPLIT = /([，,。.！!？?；;：:、～~…\s—–\-－‐‑‒―─_·•()（）【】[\]「」『』《》<>"“”'‘’/|]+)/;
/** 小句开头的应答、语气词与客气的前缀，去掉之后再整句比对（「好的不用了」「那就不考虑了」「以后别发了」「麻烦别发了」） */
const LEAD =
  /^(?:嗯+|嗯呢|哦+|噢+|喔+|啊|好的?|行|那就?|那我|算了|谢谢|谢了|多谢|真的|其实|我们?|以后|今后|往后|请|麻烦(?:你|您)?|拜托(?:你|您)?|求求?(?:你|您)们?|ok(?:ay)?|okk+)+/;
/** 句末的客气话与语气词（「不用了谢谢」「别发了哈」「不用了thx」）。吗、呢、么、嘛、吧不在里面：带着它们的是在问或在犹豫 */
const TAIL = /(?:谢谢(?:你|您|你们|啦|了)?|多谢|感谢|哈+|啊|呀|啦|哦+|噢|喔|哟|嗷|拜拜|再见|thx|thanks?|ok|bye(?:bye)?)+$/;
const ASKING = /[吗呢么嘛吧]$/;
/**
 * 整个小句只是客气话或应答：和拒绝小句放在一起不改变意思（「不用了，谢谢」「好的，不用了」「不需要了，有需要再找您」）。
 * 「好吧」「行吧」带「吧」也是应答，不是在犹豫（犹豫的「不用了吧」是拒绝小句本身带着吧）
 */
const ACK =
  /^(?:谢谢(?:你|您|你们)?(?:的)?(?:推荐|介绍|耐心|帮助|帮忙|关心|好意|解答|服务)?(?:啦|了)?|谢了|多谢|感谢|好的?|好吧|好滴|好哒|行吧?|那好吧?|嗯+|嗯呢|哦+|噢+|喔+|啊|哈+|呵呵|拜拜|再见|bye(?:bye)?|ok(?:ay)?|okk+|thx|thanks?|收到|知道了|明白了?|辛苦了?|辛苦(?:你|您)了|麻烦(?:你|您)?了|打扰了|不好意思|抱歉|有需要(?:的话)?我?(?:会|再)?(?:找|联系)(?:你|您)们?的?)+$/;

const OPT_OUT: readonly RegExp[] = [
  // 不用了、不需要了、都不用了
  /^(?:都|也|真)?(?:不用|不需要|不必)了$/,
  // 别发了、别再发了、不要再给我发消息了、不用再联系我了、别打扰我了（「不用发了」没有「再」，多半说的是不用发某样东西，不算）
  /^(?:你们?|您)?(?:别再?|甭再?|不要再?|不用再)(?:给我|跟我|和我)?(?:发|推|推送|打扰|骚扰|联系|烦)(?:我|消息|信息)?(?:给我)?了$/,
  // 已经在别家订了、已经订了别家的了
  /^(?:已经|已)(?:在)?(?:别家|别的地方|别处|其他家|其它家|其他平台|其它平台)(?:订|定|买|报|下单)(?:好)?了$/,
  /^(?:已经|已)(?:订|定|买|报)(?:了|好了)?(?:别家|别的家|其他家|其它家)(?:的)?了?$/,
  // 不考虑了、就不考虑了
  /^(?:就|都)?不考虑了$/,
];

/** 归一：全角转半角、英文小写、繁体转简体，emoji 与微信表情码换成空格（当分隔） */
function normalize(text: string): string {
  return text
    .normalize('NFKC')
    .toLowerCase()
    .replace(/thank\s+you/g, 'thanks')
    .replace(TRAD_RE, (ch) => TRAD[ch] ?? ch)
    .replace(WECHAT_FACE, ' ')
    .replace(EMOJI, ' ');
}

/** 小句里连着说了几遍同一句：「不用了不用了」→「不用了」 */
const fold = (s: string): string => s.replace(/^(.+?)\1+$/u, '$1');

/** 这一小句（已去掉边界标点）是什么：空的、拒绝、客气话或应答、别的内容。asked：后面跟着问号 */
function clauseKind(raw: string, asked: boolean): 'empty' | 'refuse' | 'ack' | 'other' {
  const c = raw.trim();
  if (!c) return 'empty';
  if (asked) return 'other';
  const core = fold(c.replace(TAIL, '').replace(LEAD, ''));
  if (!ASKING.test(c) && OPT_OUT.some((re) => re.test(core))) return 'refuse';
  if (!core || ACK.test(core) || ACK.test(c)) return 'ack';
  return 'other';
}

/** 客户这句话是不是明确拒绝跟进：至少一个拒绝小句，其余小句只有拒绝或客气话、应答 */
export function followupOptOutOf(text: string): boolean {
  const parts = normalize(text).split(CLAUSE_SPLIT);
  let refused = false;
  // split 带捕获组：奇数位是边界，偶数位是小句。边界里有问号，前面那一小句就是在问
  for (let i = 0; i < parts.length; i += 2) {
    const kind = clauseKind(parts[i] ?? '', /[？?]/.test(parts[i + 1] ?? ''));
    if (kind === 'other') return false;
    if (kind === 'refuse') refused = true;
  }
  return refused;
}
